export type SeedResult = { products: number; sessions: number }

/**
 * Idempotent: upserts by stable keys (product slug; session product + start instant), so it can
 * run any number of times without duplicating rows. Re-running resets these rows to the values above.
 */
export async function seedCatalog(prisma: PrismaClient): Promise<SeedResult> {
  await assertUtcSession(prisma)
  return prisma.$transaction(async (tx) => {
    const productIds = new Map<string, string>()
    for (const product of SEED_PRODUCTS) {
      const { slug, ...fields } = product
      const saved = await tx.product.upsert({
        where: { slug },
        create: { slug, ...fields },
        update: fields,
        select: { id: true },
      })
      productIds.set(slug, saved.id)
    }

    for (const session of SEED_SESSIONS) {
      const { productSlug, ...fields } = session
      const productId = productIds.get(productSlug)
      if (!productId) throw new Error(`Seed session refers to unknown product "${productSlug}"`)
      await tx.session.upsert({
        where: { productId_startsAt: { productId, startsAt: fields.startsAt } },
        create: { productId, ...fields },
        update: fields,
      })
    }

    return { products: SEED_PRODUCTS.length, sessions: SEED_SESSIONS.length }
  })
}
